    (function(){
        var CART_KEY = 'jj_cart';

        function getCart() {
            try { return JSON.parse(localStorage.getItem(CART_KEY)) || []; }
            catch(e) { return []; }
        }
        function saveCart(cart) {
            localStorage.setItem(CART_KEY, JSON.stringify(cart));
        }
        function formatRp(n) {
            return 'Rp ' + n.toString().replace(/\B(?=(\d{3})+(?!\d))/g, '.');
        }

        window.addToCart = function(id, name, price, image, maxStok) {
            var cart = getCart();
            var found = false;
            for (var i = 0; i < cart.length; i++) {
                if (cart[i].id === id) {
                    if (cart[i].qty < maxStok) cart[i].qty++;
                    found = true;
                    break;
                }
            }
            if (!found) {
                cart.push({ id: id, name: name, price: price, image: image, qty: 1, maxStok: maxStok });
            }
            saveCart(cart);
            renderCart();
            // open drawer
            document.getElementById('cartOverlay').classList.add('active');
            document.getElementById('cartDrawer').classList.add('active');
            document.body.style.overflow = 'hidden';
        };

        window.toggleCartDrawer = function() {
            var overlay = document.getElementById('cartOverlay');
            var drawer = document.getElementById('cartDrawer');
            var isOpen = drawer.classList.contains('active');
            if (isOpen) {
                overlay.classList.remove('active');
                drawer.classList.remove('active');
                document.body.style.overflow = '';
            } else {
                overlay.classList.add('active');
                drawer.classList.add('active');
                document.body.style.overflow = 'hidden';
            }
        };

        window.changeQty = function(id, delta) {
            var cart = getCart();
            for (var i = 0; i < cart.length; i++) {
                if (cart[i].id === id) {
                    cart[i].qty += delta;
                    if (cart[i].qty <= 0) { cart.splice(i, 1); }
                    else if (cart[i].qty > cart[i].maxStok) { cart[i].qty = cart[i].maxStok; }
                    break;
                }
            }
            saveCart(cart);
            renderCart();
        };

        window.removeFromCart = function(id) {
            var cart = getCart();
            cart = cart.filter(function(item) { return item.id !== id; });
            saveCart(cart);
            renderCart();
        };

        function renderCart() {
            var cart = getCart();
            var body = document.getElementById('cartDrawerBody');
            var footer = document.getElementById('cartDrawerFooter');
            var badge = document.getElementById('navCartBadge');
            var badgeMobile = document.getElementById('navCartBadgeMobile');
            var totalCount = 0;
            var totalPrice = 0;

            for (var i = 0; i < cart.length; i++) {
                totalCount += cart[i].qty;
                totalPrice += cart[i].qty * cart[i].price;
            }

            // badge
            var badges = [badge, badgeMobile];
            for (var b = 0; b < badges.length; b++) {
                if (!badges[b]) continue;
                if (totalCount > 0) {
                    badges[b].textContent = totalCount > 99 ? '99+' : totalCount;
                    badges[b].classList.add('has-items');
                } else {
                    badges[b].classList.remove('has-items');
                }
            }

            if (cart.length === 0) {
                body.innerHTML = '<div class="cart-drawer-empty"><i class="fa fa-shopping-basket"></i>Keranjang masih kosong</div>';
                footer.style.display = 'none';
                return;
            }

            var html = '';
            for (var i = 0; i < cart.length; i++) {
                var c = cart[i];
                html += '<div class="cart-item">'
                    + '<div class="cart-item-img"><img src="' + c.image + '" alt="' + c.name + '"></div>'
                    + '<div class="cart-item-info">'
                    + '<div class="cart-item-name">' + c.name + '</div>'
                    + '<div class="cart-item-price">' + formatRp(c.price) + '</div>'
                    + '<div class="cart-item-qty">'
                    + '<button onclick="changeQty(' + c.id + ', -1)">−</button>'
                    + '<span>' + c.qty + '</span>'
                    + '<button onclick="changeQty(' + c.id + ', 1)">+</button>'
                    + '</div></div>'
                    + '<button class="cart-item-remove" onclick="removeFromCart(' + c.id + ')" title="Hapus"><i class="fa fa-trash"></i></button>'
                    + '</div>';
            }
            body.innerHTML = html;
            footer.style.display = 'block';
            document.getElementById('cartDrawerTotal').textContent = formatRp(totalPrice);
        }

        // Init on page load
        renderCart();

        window.checkoutViaWhatsApp = function() {
            var cart = getCart();
            if (cart.length === 0) {
                alert('Keranjang masih kosong.');
                return;
            }

            var totalPrice = 0;
            var lines = [];
            lines.push('Halo, saya ingin melakukan transaksi tanpa melakukan pendaftaran di web jajanemas, tolong di bantu.');
            lines.push('');
            lines.push('Berikut adalah transaksi yang akan saya lakukan:');
            lines.push('================================');
            for (var i = 0; i < cart.length; i++) {
                var c = cart[i];
                var subtotal = c.qty * c.price;
                totalPrice += subtotal;
                lines.push(
                    (i + 1) + '. *' + c.name + '*'
                    + '\n   Harga: ' + formatRp(c.price)
                    + '\n   Jumlah: ' + c.qty
                    + '\n   Subtotal: ' + formatRp(subtotal)
                );
            }
            lines.push('================================');
